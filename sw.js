async function precacheAssets() {
  const cache = await caches.open(CACHE_NAME);
  // Limit reads so offline installation does not flood the first song.
  const priority = path => /\.(mp3|ogg|sf2)$/.test(path) ? 2 : /\.(txt|json)$/.test(path) && path.includes('/assets/') ? 1 : 0;
  const assets = [...ASSETS_TO_CACHE].sort((a,b)=>priority(a)-priority(b));
  let cursor = 0;
  const failures = [];
  await Promise.all(Array.from({ length: 6 }, async () => {
    while (cursor < assets.length) {
      const url = assets[cursor++];
      try { await cache.add(url); } catch(error) { failures.push(url); }
    }
  }));
  if (failures.length) console.warn('[SW] Offline assets unavailable:', failures);
}

self.addEventListener('install', (e) => {
  e.waitUntil(precacheAssets().then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(
        keys.filter((key) => key.startsWith('tabs-chords-pro-') && key !== CACHE_NAME).map((key) => caches.delete(key))
      )
    ).then(() => self.clients.claim())
  );
});

self.addEventListener('message', (event) => {
  if (event.data?.type !== 'OFFLINE_DIAGNOSTICS') return;
  const replyPort = event.ports?.[0];
  if (!replyPort) return;

  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    const cachedUrls = new Set((await cache.keys()).map(request => request.url));
    const resources = ASSETS_TO_CACHE.map(path => ({path,available:cachedUrls.has(new URL(path,self.location.href).href)}));
    replyPort.postMessage({
      type: 'OFFLINE_DIAGNOSTICS_RESULT',
      cacheName: CACHE_NAME,
      resources
    });
  })().catch((error) => {
    replyPort.postMessage({
      type: 'OFFLINE_DIAGNOSTICS_RESULT',
      error: String(error?.message || error),
      resources: []
    });
  }));
});

self.addEventListener('fetch', (e) => {
  // Solo interceptar GET. Ignorar chrome-extension, data URIs, etc.
  if (e.request.method !== 'GET') return;
  const url = new URL(e.request.url);
  if (url.protocol !== 'http:' && url.protocol !== 'https:') return;
  if (url.origin !== self.location.origin) return;

  // Estrategia: Network-First para HTML y JS (siempre frescos),
  //             Cache-First para assets estáticos (CSS, fonts, woff2, sf2)
  const isAsset = /\.(css|json|txt|mp3|wav|ogg|woff2?|ttf|eot|png|jpg|jpeg|svg|ico|sf2|mjs)(\?.*)?$/.test(url.pathname);

  if (isAsset) {
    // Cache-First: responde inmediatamente desde caché, si falla → red
    e.respondWith(
      caches.match(e.request, { ignoreSearch: true }).then((cached) => {
        if (cached) return cached;
        return fetch(e.request).then((res) => {
          if (res && res.ok) {
            const clone = res.clone();
            caches.open(CACHE_NAME).then((c) => c.put(e.request, clone));
          }
          return res;
        }).catch(() => new Response('', { status: 408, statusText: 'Offline' }));
      })
    );
  } else {
    // Network-First: intenta red, si falla usa caché, si tampoco → fallback HTML
    e.respondWith(
      fetch(e.request).then((res) => {
        if (res && res.ok) {
          const clone = res.clone();
          caches.open(CACHE_NAME).then((c) => c.put(e.request, clone));
        }
        return res;
      }).catch(() =>
        caches.match(e.request, { ignoreSearch: true }).then((cached) => {
          if (cached) return cached;
          if (e.request.mode !== 'navigate') return new Response('', { status: 503, statusText: 'Offline resource unavailable' });
          return caches.match('./index.html', { ignoreSearch: true })
            .then((fb) => fb || caches.match('./', { ignoreSearch: true }))
            .then((fb) => fb || caches.match('/index.html', { ignoreSearch: true }))
            .then((fallback) =>
              fallback || new Response('<h1>Sin conexión</h1>', {
                status: 503,
                headers: { 'Content-Type': 'text/html' }
              })
            );
        })
      )
    );
  }
});
